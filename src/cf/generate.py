"""Render CloudFormation templates from the JSON configs (stdlib only).

Usage: python src/cf/generate.py [ec2|lambda|all]
Edit src/cf/ec2/instances.json or src/cf/lambda/functions.json, then re-run.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).parent

# Inline handler code per behavior; every behavior is a Python 3 handler in index.py.
BEHAVIORS = {
    "noop": "def handler(event, context):\n    return {\"ok\": True}\n",
    "cpu": (
        "def handler(event, context):\n"
        "    total = 0\n"
        "    for i in range(int(event.get(\"n\", 5000000))):\n"
        "        total += i * i\n"
        "    return {\"total\": total}\n"
    ),
    "flaky": (
        "import random\n"
        "def handler(event, context):\n"
        "    if random.random() < float(event.get(\"fail_rate\", 0.3)):\n"
        "        raise RuntimeError(\"simulated failure\")\n"
        "    return {\"ok\": True}\n"
    ),
}


def logical_id(name: str) -> str:
    return "".join(p.capitalize() for p in re.split(r"[^A-Za-z0-9]+", name) if p)


def ec2_template(cfg: dict) -> dict:
    suffix = cfg.get("name_suffix", "")
    resources = {
        "InstanceRole": {
            "Type": "AWS::IAM::Role",
            "Properties": {
                "AssumeRolePolicyDocument": {
                    "Version": "2012-10-17",
                    "Statement": [{"Effect": "Allow", "Principal": {"Service": "ec2.amazonaws.com"}, "Action": "sts:AssumeRole"}],
                },
                "ManagedPolicyArns": ["arn:aws:iam::aws:policy/AmazonSSMManagedInstanceCore"],
            },
        },
        "InstanceProfile": {"Type": "AWS::IAM::InstanceProfile", "Properties": {"Roles": [{"Ref": "InstanceRole"}]}},
    }
    outputs = {}
    for item in cfg["instances"]:
        lid = logical_id(item["name"])
        props = {
            "InstanceType": item["instance_type"],
            "ImageId": item.get("ami") or {"Ref": "LatestAmiId"},
            "IamInstanceProfile": {"Ref": "InstanceProfile"},
            "SubnetId": {"Fn::If": ["HasSubnet", {"Ref": "SubnetId"}, {"Ref": "AWS::NoValue"}]},
            "BlockDeviceMappings": [
                {"DeviceName": "/dev/xvda", "Ebs": {"VolumeSize": item.get("volume_gb", 8), "VolumeType": item.get("volume_type", "gp3")}}
            ],
            "Tags": [
                {"Key": "Name", "Value": item["name"] + suffix},
                {"Key": "Purpose", "Value": "awsro-test"},
                {"Key": "Profile", "Value": item.get("profile", "idle")},
            ],
        }
        resources[lid] = {"Type": "AWS::EC2::Instance", "Properties": props}
        outputs[lid + "Id"] = {"Value": {"Ref": lid}}
    return {
        "AWSTemplateFormatVersion": "2010-09-09",
        "Description": "GENERATED by src/cf/generate.py from instances.json - do not edit by hand.",
        "Parameters": {
            "LatestAmiId": {
                "Type": "AWS::SSM::Parameter::Value<AWS::EC2::Image::Id>",
                "Default": "/aws/service/ami-amazon-linux-latest/al2023-ami-kernel-default-x86_64",
            },
            "SubnetId": {"Type": "String", "Default": "", "Description": "Optional subnet; empty uses the default VPC."},
        },
        "Conditions": {"HasSubnet": {"Fn::Not": [{"Fn::Equals": [{"Ref": "SubnetId"}, ""]}]}},
        "Resources": resources,
        "Outputs": outputs,
    }


def lambda_template(cfg: dict) -> dict:
    suffix = cfg.get("name_suffix", "")
    resources = {
        "FunctionRole": {
            "Type": "AWS::IAM::Role",
            "Properties": {
                "AssumeRolePolicyDocument": {
                    "Version": "2012-10-17",
                    "Statement": [{"Effect": "Allow", "Principal": {"Service": "lambda.amazonaws.com"}, "Action": "sts:AssumeRole"}],
                },
                "ManagedPolicyArns": ["arn:aws:iam::aws:policy/service-role/AWSLambdaBasicExecutionRole"],
            },
        }
    }
    for item in cfg["functions"]:
        behavior = item.get("behavior", "noop")
        if behavior not in BEHAVIORS:
            raise SystemExit(f"Unknown behavior '{behavior}' for {item['name']}; use one of {sorted(BEHAVIORS)}")
        resources[logical_id(item["name"])] = {
            "Type": "AWS::Lambda::Function",
            "Properties": {
                "FunctionName": item["name"] + suffix,
                "Runtime": item.get("runtime", "python3.12"),
                "Handler": "index.handler",
                "MemorySize": item.get("memory", 128),
                "Timeout": item.get("timeout", 10),
                "Role": {"Fn::GetAtt": ["FunctionRole", "Arn"]},
                "Tags": [{"Key": "Purpose", "Value": "awsro-test"}],
                "Code": {"ZipFile": BEHAVIORS[behavior]},
            },
        }
    return {
        "AWSTemplateFormatVersion": "2010-09-09",
        "Description": "GENERATED by src/cf/generate.py from functions.json - do not edit by hand.",
        "Resources": resources,
    }


JOBS = {
    "ec2": ("ec2/instances.json", ec2_template, "ec2/template.json"),
    "lambda": ("lambda/functions.json", lambda_template, "lambda/template.json"),
}


def main() -> None:
    which = sys.argv[1] if len(sys.argv) > 1 else "all"
    if which not in {*JOBS, "all"}:
        raise SystemExit("Usage: generate.py [ec2|lambda|all]")
    for key, (cfg_path, render, out_path) in JOBS.items():
        if which in (key, "all"):
            template = render(json.loads((ROOT / cfg_path).read_text()))
            (ROOT / out_path).write_text(json.dumps(template, indent=2) + "\n")
            print(f"wrote src/cf/{out_path}")


if __name__ == "__main__":
    main()
